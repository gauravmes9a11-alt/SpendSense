"""SpendSense transaction embeddings and cosine-distance search.

Local-first behaviour:
- Primary: BAAI/bge-small-en-v1.5 through FastEmbed.
- If FastEmbed is unavailable or its model cannot run: deterministic SHA-256 fallback.
- Optional remote providers: OpenAI or Gemini, selected explicitly with EMBEDDING_PROVIDER.

Set EMBEDDING_PROVIDER=fastembed (default), openai, gemini, or fallback.
Do not mix vectors generated by different models; sync_missing_embeddings()
regenerates rows whose stored model differs from the model used for generation.
"""
from __future__ import annotations

import hashlib
import json
import logging
import os
import re
import urllib.request
from typing import Any, Optional

import numpy as np

log = logging.getLogger("spendsense.embeddings")

_VECTOR_CACHE: dict[int, np.ndarray] = {}
_fastembed_model: Any = None
_ACTIVE_MODEL_NAME: Optional[str] = None


def _provider() -> str:
    value = os.getenv("EMBEDDING_PROVIDER", "fastembed").strip().lower()
    if value not in {"fastembed", "openai", "gemini", "fallback"}:
        log.warning("Unknown EMBEDDING_PROVIDER=%r; using deterministic fallback.", value)
        return "fallback"
    return value


def _get_fastembed_model():
    """Load FastEmbed once. Return None when it is unavailable."""
    global _fastembed_model

    if _fastembed_model is False:
        return None
    if _fastembed_model is not None:
        return _fastembed_model

    try:
        os.environ.setdefault("HF_HUB_DISABLE_SYMLINKS_WARNING", "1")
        from fastembed import TextEmbedding

        _fastembed_model = TextEmbedding(model_name="BAAI/bge-small-en-v1.5")
        log.info("Initialized FastEmbed model BAAI/bge-small-en-v1.5")
        return _fastembed_model
    except Exception as exc:
        log.warning("FastEmbed unavailable; deterministic fallback will be used: %s", exc)
        _fastembed_model = False
        return None


def _embed_openai(texts: list[str], api_key: str) -> Optional[list[list[float]]]:
    """Generate embeddings using OpenAI's embeddings REST endpoint."""
    try:
        payload = json.dumps({
            "input": texts,
            "model": "text-embedding-3-small",
        }).encode("utf-8")
        request = urllib.request.Request(
            "https://api.openai.com/v1/embeddings",
            data=payload,
            headers={
                "Content-Type": "application/json",
                "Authorization": f"Bearer {api_key}",
            },
        )
        with urllib.request.urlopen(request, timeout=20) as response:
            data = json.loads(response.read().decode("utf-8"))
        items = sorted(data["data"], key=lambda item: item["index"])
        vectors = [item["embedding"] for item in items]
        return vectors if len(vectors) == len(texts) else None
    except Exception:
        log.exception("OpenAI embedding request failed.")
        return None


def _embed_gemini(texts: list[str], api_key: str) -> Optional[list[list[float]]]:
    """Generate embeddings using Google's text-embedding-004 endpoint."""
    try:
        vectors: list[list[float]] = []
        for value in texts:
            url = (
                "https://generativelanguage.googleapis.com/v1beta/"
                "models/text-embedding-004:embedContent"
                f"?key={api_key}"
            )
            payload = json.dumps({
                "model": "models/text-embedding-004",
                "content": {"parts": [{"text": value}]},
            }).encode("utf-8")
            request = urllib.request.Request(
                url,
                data=payload,
                headers={"Content-Type": "application/json"},
            )
            with urllib.request.urlopen(request, timeout=20) as response:
                data = json.loads(response.read().decode("utf-8"))
            vectors.append(data["embedding"]["values"])
        return vectors if len(vectors) == len(texts) else None
    except Exception:
        log.exception("Gemini embedding request failed.")
        return None


def _fallback_embed(texts: list[str], dim: int = 384) -> list[list[float]]:
    """Stable feature-hashing fallback; identical input gives identical vectors."""
    output: list[list[float]] = []

    for value in texts:
        vector = np.zeros(dim, dtype=np.float32)
        tokens = re.findall(r"\b\w+\b", (value or "").lower())

        for token in tokens:
            word_hash = int.from_bytes(
                hashlib.sha256(token.encode("utf-8")).digest()[:8],
                byteorder="big",
            ) % dim
            vector[word_hash] += 1.0

            for index in range(max(0, len(token) - 2)):
                trigram = token[index:index + 3]
                trigram_hash = int.from_bytes(
                    hashlib.sha256(trigram.encode("utf-8")).digest()[:8],
                    byteorder="big",
                ) % dim
                vector[trigram_hash] += 0.5

        norm = float(np.linalg.norm(vector))
        if norm > 0:
            vector /= norm
        output.append(vector.tolist())

    return output


def get_model_name() -> str:
    """Return the model currently selected/available for embedding generation."""
    global _ACTIVE_MODEL_NAME

    provider = _provider()

    if provider == "fastembed":
        if _get_fastembed_model() is not None:
            _ACTIVE_MODEL_NAME = "BAAI/bge-small-en-v1.5"
        else:
            _ACTIVE_MODEL_NAME = "SpendSense-Semantic-v1"
    elif provider == "openai":
        _ACTIVE_MODEL_NAME = "openai/text-embedding-3-small"
    elif provider == "gemini":
        _ACTIVE_MODEL_NAME = "gemini/text-embedding-004"
    else:
        _ACTIVE_MODEL_NAME = "SpendSense-Semantic-v1"

    return _ACTIVE_MODEL_NAME


def generate_embeddings_with_model(
    texts: list[str],
) -> tuple[str, list[list[float]]]:
    """Return both vectors and the exact model identity used."""
    global _ACTIVE_MODEL_NAME, _fastembed_model

    if not texts:
        return get_model_name(), []

    provider = _provider()

    if provider == "fastembed":
        model = _get_fastembed_model()
        if model is not None:
            try:
                vectors = [np.asarray(v, dtype=np.float32).tolist() for v in model.embed(texts)]
                if len(vectors) == len(texts) and all(vectors):
                    _ACTIVE_MODEL_NAME = "BAAI/bge-small-en-v1.5"
                    return _ACTIVE_MODEL_NAME, vectors
                raise ValueError("FastEmbed returned an unexpected number of vectors.")
            except Exception:
                log.exception("FastEmbed inference failed; switching to deterministic fallback.")
                _fastembed_model = False

        _ACTIVE_MODEL_NAME = "SpendSense-Semantic-v1"
        return _ACTIVE_MODEL_NAME, _fallback_embed(texts)

    if provider == "openai":
        key = os.getenv("OPENAI_API_KEY", "").strip()
        vectors = _embed_openai(texts, key) if key else None
        if vectors:
            _ACTIVE_MODEL_NAME = "openai/text-embedding-3-small"
            return _ACTIVE_MODEL_NAME, vectors
        log.warning("OpenAI unavailable or key missing; using deterministic fallback.")
        _ACTIVE_MODEL_NAME = "SpendSense-Semantic-v1"
        return _ACTIVE_MODEL_NAME, _fallback_embed(texts)

    if provider == "gemini":
        key = os.getenv("GEMINI_API_KEY", "").strip()
        vectors = _embed_gemini(texts, key) if key else None
        if vectors:
            _ACTIVE_MODEL_NAME = "gemini/text-embedding-004"
            return _ACTIVE_MODEL_NAME, vectors
        log.warning("Gemini unavailable or key missing; using deterministic fallback.")
        _ACTIVE_MODEL_NAME = "SpendSense-Semantic-v1"
        return _ACTIVE_MODEL_NAME, _fallback_embed(texts)

    _ACTIVE_MODEL_NAME = "SpendSense-Semantic-v1"
    return _ACTIVE_MODEL_NAME, _fallback_embed(texts)


def generate_embeddings(texts: list[str]) -> list[list[float]]:
    """Compatibility helper returning vectors only."""
    return generate_embeddings_with_model(texts)[1]


def generate_embedding(value: str) -> list[float]:
    """Generate one vector for a query string."""
    vectors = generate_embeddings([value])
    return vectors[0] if vectors else []


def transaction_text(tx: dict[str, Any]) -> str:
    """Build a consistent text representation of a transaction."""
    merchant = tx.get("merchant_name") or "Unknown merchant"
    category = tx.get("category_name") or "Uncategorized"
    description = tx.get("description") or ""
    transaction_type = tx.get("transaction_type") or "EXPENSE"

    parts = [f"Merchant: {merchant}", f"Category: {category}"]
    if description:
        parts.append(f"Description: {description}")
    parts.append(f"Type: {transaction_type}")
    return ". ".join(parts)


def cosine_distance(
    vec_a: np.ndarray | list[float],
    vec_b: np.ndarray | list[float],
) -> float:
    """Return cosine distance (1 - cosine similarity)."""
    a = np.asarray(vec_a, dtype=np.float32)
    b = np.asarray(vec_b, dtype=np.float32)

    if a.ndim != 1 or b.ndim != 1 or a.shape != b.shape:
        return 1.0

    norm_a = float(np.linalg.norm(a))
    norm_b = float(np.linalg.norm(b))
    if norm_a == 0.0 or norm_b == 0.0:
        return 1.0

    similarity = float(np.dot(a, b) / (norm_a * norm_b))
    similarity = max(-1.0, min(1.0, similarity))
    return max(0.0, 1.0 - similarity)


def ensure_schema() -> None:
    """Create the embedding table if it does not already exist."""
    import db
    from sqlalchemy import text

    statement = """
    CREATE TABLE IF NOT EXISTS transaction_embeddings (
        transaction_id BIGINT PRIMARY KEY,
        embedding_model VARCHAR(120) NOT NULL,
        dimensions INT NOT NULL,
        embedding JSON NOT NULL,
        text_content VARCHAR(500) NOT NULL,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            ON UPDATE CURRENT_TIMESTAMP,
        CONSTRAINT fk_tx_embedding
            FOREIGN KEY (transaction_id)
            REFERENCES transactions(transaction_id)
            ON DELETE CASCADE
    ) ENGINE=InnoDB
    """

    try:
        with db.engine.begin() as connection:
            connection.execute(text(statement))
    except Exception:
        # Do not hide the failure from logs; later DB operations may still fail.
        log.exception("Could not ensure transaction_embeddings table exists.")
        raise


def load_vector_cache() -> None:
    """Load only vectors belonging to the currently active model."""
    global _VECTOR_CACHE
    import db

    ensure_schema()
    active_model = get_model_name()

    rows = db.query("""
        SELECT transaction_id, embedding_model, dimensions, embedding
        FROM transaction_embeddings
        WHERE embedding_model = :model
    """, {"model": active_model})

    new_cache: dict[int, np.ndarray] = {}
    for row in rows:
        try:
            raw = row["embedding"]
            if isinstance(raw, str):
                raw = json.loads(raw)

            vector = np.asarray(raw, dtype=np.float32)
            expected_dimensions = int(row["dimensions"])

            if vector.ndim != 1 or vector.size != expected_dimensions or vector.size == 0:
                log.warning(
                    "Skipping malformed embedding for transaction %s.",
                    row["transaction_id"],
                )
                continue

            new_cache[int(row["transaction_id"])] = vector
        except Exception:
            log.exception(
                "Could not load embedding for transaction %s.",
                row.get("transaction_id"),
            )

    _VECTOR_CACHE = new_cache
    log.info("Loaded %d transaction embeddings into cache.", len(_VECTOR_CACHE))


def sync_missing_embeddings() -> int:
    """Insert missing embeddings and regenerate rows from a different model.

    Returns the number of rows inserted/updated. Errors are logged and return 0
    so an optional semantic-search feature does not crash the API process.
    """
    global _VECTOR_CACHE
    import db
    from sqlalchemy import text

    try:
        ensure_schema()
        expected_model = get_model_name()

        rows = db.query("""
            SELECT
                t.transaction_id,
                m.merchant_name,
                c.category_name,
                t.description,
                t.transaction_type
            FROM transactions AS t
            JOIN merchants AS m ON m.merchant_id = t.merchant_id
            JOIN categories AS c ON c.category_id = t.category_id
            LEFT JOIN transaction_embeddings AS te
                ON te.transaction_id = t.transaction_id
            WHERE te.transaction_id IS NULL
               OR te.embedding_model <> :model
        """, {"model": expected_model})

        if not rows:
            load_vector_cache()
            return 0

        texts = [transaction_text(row) for row in rows]
        actual_model, vectors = generate_embeddings_with_model(texts)

        if len(vectors) != len(rows):
            raise RuntimeError("Embedding count does not match transaction count.")

        with db.engine.begin() as connection:
            for row, vector, content in zip(rows, vectors, texts):
                if not vector:
                    raise RuntimeError(
                        f"Empty embedding for transaction {row['transaction_id']}."
                    )

                connection.execute(
                    text("""
                        INSERT INTO transaction_embeddings
                            (transaction_id, embedding_model, dimensions,
                             embedding, text_content)
                        VALUES
                            (:transaction_id, :model, :dimensions,
                             :embedding, :content)
                        ON DUPLICATE KEY UPDATE
                            embedding_model = VALUES(embedding_model),
                            dimensions = VALUES(dimensions),
                            embedding = VALUES(embedding),
                            text_content = VALUES(text_content)
                    """),
                    {
                        "transaction_id": row["transaction_id"],
                        "model": actual_model,
                        "dimensions": len(vector),
                        "embedding": json.dumps(vector),
                        "content": content[:500],
                    },
                )

        load_vector_cache()
        return len(rows)

    except Exception:
        log.exception("Embedding synchronization failed; API process will remain running.")
        return 0


def calculate_distances_for_query(
    query: str,
    target_ids: Optional[list[int]] = None,
) -> dict[int, float]:
    """Return transaction ID -> cosine distance for the selected transaction IDs."""
    if not query or not query.strip():
        return {}

    try:
        active_model = get_model_name()

        # Cache may contain vectors from a previous provider/model selection.
        if not _VECTOR_CACHE or any(
            vec.ndim != 1 for vec in _VECTOR_CACHE.values()
        ):
            load_vector_cache()

        # Ensure the query vector is produced by the same model as stored vectors.
        query_model, query_vectors = generate_embeddings_with_model([query.strip()])
        if not query_vectors:
            return {}

        if query_model != active_model:
            # The provider fell back during inference; do not compare unlike models.
            log.warning(
                "Query model %s differs from active model %s; skipping semantic search.",
                query_model,
                active_model,
            )
            return {}

        query_vector = np.asarray(query_vectors[0], dtype=np.float32)
        if query_vector.ndim != 1 or query_vector.size == 0:
            return {}

        query_norm = float(np.linalg.norm(query_vector))
        if query_norm == 0.0:
            return {}

        candidates = target_ids if target_ids is not None else list(_VECTOR_CACHE)
        distances: dict[int, float] = {}

        for transaction_id in candidates:
            vector = _VECTOR_CACHE.get(int(transaction_id))
            if vector is None or vector.shape != query_vector.shape:
                continue

            vector_norm = float(np.linalg.norm(vector))
            if vector_norm == 0.0:
                continue

            similarity = float(
                np.dot(query_vector, vector) / (query_norm * vector_norm)
            )
            similarity = max(-1.0, min(1.0, similarity))
            distances[int(transaction_id)] = round(max(0.0, 1.0 - similarity), 4)

        return distances

    except Exception:
        log.exception("Semantic distance calculation failed.")
        return {}
